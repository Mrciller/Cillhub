// v3 smoke: stage view, soundboard, voice connection details, scheduled events, voice processing settings.
const assert = require('node:assert/strict')
const h = require('./smoke-v3-harness.cjs')

/** Sets a range input the way a drag does (Playwright cannot fill ranges). */
const setRange = (loc, v) => loc.evaluate((el, v) => {
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, String(v))
  el.dispatchEvent(new Event('input', { bubbles: true }))
}, v)

async function run(browser, errors) {
  const { page, ctx, ops, posted } = await h.open(browser, { errors, url: `/channels/${h.G}/305` })
  const nav = page.getByRole('navigation', { name: 'Nightfall Gaming channels' })

  // Stage: topic banner, speakers, hands raised (moderator view), audience after joining.
  const stage = page.getByRole('main', { name: 'Stage channel Town Hall' })
  await stage.getByRole('heading', { name: 'Season kickoff Q&A' }).waitFor()
  await stage.getByRole('list', { name: 'Speakers' }).getByRole('button', { name: /bob/ }).waitFor()
  const requests = stage.getByRole('list', { name: 'Requested to Speak' })
  await requests.getByText('carol', { exact: true }).waitFor()
  await stage.getByRole('button', { name: 'Join Stage' }).click()
  assert.equal(ops.findLast((f) => f.op === 4).d.channel_id, '305')
  await stage.getByRole('list', { name: 'Audience' }).getByRole('button', { name: /ciller/ }).waitFor()
  await stage.getByRole('button', { name: 'Become a Speaker' }).waitFor()
  await page.mouse.move(0, 0)
  await page.screenshot({ path: h.shot('stage') })
  await requests.getByRole('button', { name: 'Invite carol to Speak' }).click()
  await page.waitForTimeout(100)
  const invite = posted.find((p) => p.pathname.endsWith('/voice-states/102'))
  assert.deepEqual(invite.body, { channel_id: '305', suppress: false })
  console.log('ok v3-events - stage view: topic, speakers, raised hand, audience, invite to speak')

  // Soundboard from the voice panel in a voice channel (sounds go through the gateway, so it works without LiveKit).
  await nav.getByRole('button', { name: /^Lounge/ }).click()
  await page.waitForURL('**/channels/200/302')
  const panel = page.getByRole('region', { name: 'Voice connection' })
  await panel.getByText('Voice Unavailable').waitFor()
  await panel.getByRole('button', { name: 'Soundboard' }).click()
  const board = page.getByRole('dialog', { name: 'Soundboard' })
  // scoped: another guild's sounds may already be loaded and listed in their own section
  await board.getByRole('region', { name: 'Nightfall Gaming' }).getByRole('button', { name: 'Play airhorn' }).click()
  await page.waitForTimeout(100)
  assert.deepEqual(posted.find((p) => p.pathname.endsWith('/channels/302/send-soundboard-sound')).body, { sound_id: '990' })
  await page.keyboard.press('Escape')
  console.log('ok v3-events - soundboard popover lists and plays sounds')

  await panel.getByRole('button', { name: 'Disconnect' }).click()


  // Events: list from READY, interested toggle.
  await page.getByRole('button', { name: '1 Event', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Events' })
  const card = modal.getByRole('article', { name: 'Patch Party' })
  await card.getByText('4 interested').waitFor()
  await card.getByRole('button', { name: 'Interested' }).click()
  await card.getByText('5 interested').waitFor()
  assert.ok(posted.some((p) => p.method === 'PUT' && p.pathname.endsWith('/scheduled-events/980/users/@me')))
  await modal.getByRole('button', { name: 'Create Event' }).click()
  await page.getByRole('dialog', { name: 'Create Event' }).getByRole('radio', { name: /Stage Channel/ }).check()
  await page.getByLabel('Select a channel').selectOption({ label: 'Town Hall' })
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByLabel('Event Topic').waitFor()
  await page.keyboard.press('Escape')
  console.log('ok v3-events - events list, interested toggle, create wizard')

  // Voice processing and volume settings persist (hotfix 2 defaults: 64 kbps, DTX off).
  await page.getByRole('button', { name: 'User Settings' }).click()
  await page.getByRole('tab', { name: 'Voice & Video' }).click()
  await page.getByLabel('Noise Suppression').selectOption('off')
  assert.equal(await page.getByRole('checkbox', { name: /Save Bandwidth When Silent/ }).isChecked(), false)
  assert.equal(await page.getByLabel('Voice Quality').inputValue(), '64000')
  await page.getByLabel('Voice Quality').selectOption({ label: '96 kbps' })
  const input = page.getByRole('slider', { name: /Input Volume/ })
  await setRange(input, 150)
  await setRange(page.getByRole('slider', { name: /Output Volume/ }), 80)
  let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('voice-settings')))
  assert.deepEqual([saved.noiseSuppression, saved.dtx, saved.bitrate, saved.echoCancellation, saved.inputGain, saved.outputVolume, saved.v], ['off', false, 96000, true, 1.5, 0.8, 2])
  await input.dblclick()
  saved = await page.evaluate(() => JSON.parse(localStorage.getItem('voice-settings')))
  assert.equal(saved.inputGain, 1, 'double-click resets to 100 %')
  await page.getByRole('button', { name: 'Close settings' }).click()
  console.log('ok v3-events - voice processing settings persist')
  await ctx.close()
  await connected(browser, errors)
}

/** With a stand-in livekit-client (see the harness): ping and connection details, Go Live dialog, live stream quality, input volume. */
async function connected(browser, errors) {
  const { page, ctx } = await h.open(browser, { errors, livekit: true })
  await page.getByRole('navigation', { name: 'Nightfall Gaming channels' }).getByRole('button', { name: /^Lounge/ }).click()
  const panel = page.getByRole('region', { name: 'Voice connection' })
  await panel.getByRole('status').filter({ hasText: 'Voice Connected' }).waitFor()
  const room = await page.evaluate(() => window.__lk.room.publishDefaults)
  assert.deepEqual(room, { audioPreset: { maxBitrate: 64000 }, dtx: false, red: true }, 'publish defaults: 64 kbps, no DTX, RED')

  const ping = panel.getByRole('button', { name: 'Ping 42 ms. Show connection details' })
  await ping.click()
  await panel.getByText('UDP host').waitFor()
  await panel.getByText('opus').waitFor()
  await panel.getByText(/^\d+ kbps$/).waitFor()
  assert.equal(await ping.getAttribute('class'), 'vp-ping good')
  console.log('ok v3-events - ping with signal bars and connection details')

  await panel.getByRole('button', { name: 'Share Your Screen' }).click()
  const go = page.getByRole('dialog', { name: 'Screen Share' })
  await go.getByRole('radio', { name: '1080p' }).waitFor()
  assert.equal(await go.getByRole('radio', { name: '1080p' }).isChecked(), true)
  await go.getByRole('button', { name: 'Go Live' }).click()
  await page.waitForFunction(() => window.__lk.screen) // after the codec choice (mediaCapabilities is asynchronous)
  const share = await page.evaluate(() => window.__lk.screen)
  assert.deepEqual([share.capture.resolution, share.publish.screenShareEncoding], [{ width: 1920, height: 1080, frameRate: 30 }, { maxBitrate: 6000000, maxFramerate: 30 }])
  assert.equal(share.publish.degradationPreference, 'maintain-resolution', 'screen shares keep their resolution in both modes')
  assert.deepEqual([share.publish.videoCodec, share.publish.backupCodec], ['h264', { codec: 'vp8' }], 'Auto: H.264 (Chromium can encode it) with a VP8 backup')
  await ping.click() // details closed and opened again: the screen share rows poll while open
  await ping.click()
  const details = panel.locator('.vp-stats')
  await details.getByText('H.264 · GPU (MediaFoundationVideoEncodeAccelerator)', { exact: true }).waitFor()
  await details.getByText('1920×1080 · 30 fps', { exact: true }).waitFor()
  await details.getByText('H.264 · software (FFmpeg)', { exact: true }).waitFor()
  await details.getByText('1280×720 · 15 fps', { exact: true }).waitFor()
  console.log('ok v3-events - screen share encoder (GPU) and decoder (software) in the connection details')
  await panel.getByRole('button', { name: 'Stream Quality' }).click()
  const q = page.getByRole('dialog', { name: 'Stream Quality' })
  await q.getByText('Encoder: H.264 · GPU (MediaFoundationVideoEncodeAccelerator) · 1920×1080 · 30 fps').waitFor()
  await q.getByRole('radio', { name: '720p' }).check()
  await q.getByRole('radio', { name: '15 FPS' }).check()
  await q.getByRole('button', { name: 'Apply' }).click()
  await page.waitForFunction(() => window.__lk.params)
  const live = await page.evaluate(() => ({ c: window.__lk.constraints, e: window.__lk.params.encodings }))
  assert.deepEqual(live.c, { width: { max: 1280 }, height: { max: 720 }, frameRate: { max: 15 } })
  assert.deepEqual(live.e.map((x) => [x.maxBitrate, x.maxFramerate]), [[1500000, 15], [375000, 15]], 'all simulcast layers scaled by one factor')
  console.log('ok v3-events - Go Live dialog and live stream quality change')

  await page.getByRole('button', { name: 'User Settings' }).click()
  await page.getByRole('tab', { name: 'Voice & Video' }).click()
  await setRange(page.getByRole('slider', { name: /Input Volume/ }), 250)
  await page.waitForFunction(() => window.__lk.gain === 2.5)
  await page.getByRole('slider', { name: /Input Volume/ }).dblclick()
  await page.waitForFunction(() => window.__lk.gain === 1)
  const codec = page.getByLabel('Screen Share Encoder')
  assert.equal(await codec.inputValue(), 'auto')
  await codec.selectOption('vp8')
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('voice-settings')))).screenCodec, 'vp8')
  await page.getByRole('button', { name: 'Close settings' }).click()
  console.log('ok v3-events - input volume attaches the gain processor live and removes it at 100 %')
  await panel.getByRole('button', { name: 'Share Your Screen' }).click() // stop
  await panel.getByRole('button', { name: 'Share Your Screen' }).click()
  await page.getByRole('dialog', { name: 'Screen Share' }).getByRole('button', { name: 'Go Live' }).click()
  await page.waitForFunction(() => window.__lk.screen?.publish.videoCodec === 'vp8')
  console.log('ok v3-events - "Screen Share Encoder" setting: VP8 chosen is what the next share publishes')

  // AV1: Auto takes it only when mediaCapabilities says the GPU encodes it (powerEfficient), chosen by hand also in software
  await page.evaluate(() => {
    window.__mc = { hw: false, queries: [] }
    navigator.mediaCapabilities.encodingInfo = async (c) => (window.__mc.queries.push(c), { supported: true, smooth: true, powerEfficient: window.__mc.hw })
  })
  const restartShare = async () => {
    await panel.getByRole('button', { name: 'Share Your Screen' }).click() // stop
    await page.waitForFunction(() => !window.__lk.screen)
    await panel.getByRole('button', { name: 'Share Your Screen' }).click()
    await page.getByRole('dialog', { name: 'Screen Share' }).getByRole('button', { name: 'Go Live' }).click()
    await page.waitForFunction(() => window.__lk.screen)
    return page.evaluate(() => window.__lk.screen.publish)
  }
  await page.getByRole('button', { name: 'User Settings' }).click()
  await page.getByRole('tab', { name: 'Voice & Video' }).click()
  assert.equal(await codec.locator('option[value="av1"]').isDisabled(), false, 'this Chromium encodes AV1')
  await page.getByText('Chosen here, AV1 may be encoded by the CPU', { exact: false }).waitFor()
  await codec.selectOption('auto')
  await page.getByRole('button', { name: 'Close settings' }).click()
  let pub = await restartShare()
  assert.deepEqual([pub.videoCodec, pub.scalabilityMode, pub.backupCodec], ['h264', undefined, { codec: 'vp8' }], 'Auto without a GPU AV1 encoder: H.264')
  assert.deepEqual(await page.evaluate(() => window.__mc.queries.at(-1)), { type: 'webrtc', video: { contentType: 'video/AV1', width: 1280, height: 720, bitrate: 1500000, framerate: 15, scalabilityMode: 'L1T1' } }, 'asked for the remembered quality (720p, 15 FPS)')
  await page.evaluate(() => (window.__mc.hw = true))
  pub = await restartShare()
  assert.deepEqual([pub.videoCodec, pub.scalabilityMode, pub.backupCodec], ['av1', 'L1T1', { codec: 'h264' }], 'Auto with a GPU AV1 encoder: AV1 (L1T1 simulcast), H.264 backup')
  await page.evaluate(() => (window.__lk.encoder = { mime: 'video/AV1', impl: 'SimulcastEncoderAdapter (libaom, libaom)', hw: false }))
  if ((await ping.getAttribute('aria-expanded')) !== 'true') await ping.click()
  await panel.locator('.vp-stats').getByText('AV1 · software (libaom)', { exact: true }).waitFor()
  await panel.getByRole('button', { name: 'Stream Quality' }).click()
  await page.getByRole('dialog', { name: 'Stream Quality' }).getByText('Encoder: AV1 · software (libaom) · 1920×1080 · 30 fps').waitFor()
  await page.getByRole('dialog', { name: 'Stream Quality' }).getByRole('button', { name: 'Cancel' }).click()
  console.log('ok v3-events - Auto picks AV1 only when mediaCapabilities reports a power-efficient (GPU) encoder; AV1 in the encoder line')
  await page.evaluate(() => (window.__lk.bobAttributes.av1 = '0'))
  pub = await restartShare()
  assert.deepEqual([pub.videoCodec, pub.backupCodec], ['h264', { codec: 'vp8' }], 'no AV1 while a viewer says it gets none (participant attribute av1: 0)')
  await page.evaluate(() => delete window.__lk.bobAttributes.av1)
  assert.equal(await page.evaluate(() => window.__lk.attributes ?? null), null, 'this Chromium decodes AV1: no attribute set')
  console.log('ok v3-events - LiveKit: a viewer without AV1 (attribute av1: 0) keeps the share on H.264')
  await page.evaluate(() => (window.__mc.hw = false))
  await page.getByRole('button', { name: 'User Settings' }).click()
  await page.getByRole('tab', { name: 'Voice & Video' }).click()
  await codec.selectOption('av1')
  await page.getByRole('button', { name: 'Close settings' }).click()
  pub = await restartShare()
  assert.deepEqual([pub.videoCodec, pub.scalabilityMode, pub.backupCodec], ['av1', 'L1T1', { codec: 'h264' }], 'AV1 chosen: AV1 even without a GPU encoder')
  console.log('ok v3-events - "Screen Share Encoder" AV1 chosen: published as AV1 in software, H.264 backup')
  await ctx.close()
}

module.exports = { run }
