// user-client events a bot never gets
const USER_ONLY = new Set(['MESSAGE_ACK', 'RELATIONSHIP_ADD', 'RELATIONSHIP_REMOVE', 'CALL_CREATE', 'CALL_UPDATE', 'CALL_DELETE',
  'CHANNEL_RECIPIENT_ADD', 'CHANNEL_RECIPIENT_REMOVE', 'USER_SETTINGS_UPDATE', 'USER_GUILD_SETTINGS_UPDATE', 'USER_NOTE_UPDATE',
  'RECENT_MENTION_DELETE', 'GUILD_APPLICATION_COMMAND_INDEX_UPDATE', 'WATCH_SESSION_UPDATE', 'SCHEDULED_MESSAGE_CREATE',
  'SCHEDULED_MESSAGE_UPDATE', 'SCHEDULED_MESSAGE_DELETE', 'SAVED_MESSAGE_CREATE', 'SAVED_MESSAGE_DELETE', 'MESSAGE_REMINDER_DUE',
  'GUILD_AVATAR_DECORATIONS_UPDATE', 'INSTANCE_ANNOUNCEMENT', 'INSTANCE_SETTINGS_UPDATE', 'MODULE_UI_EVENT', 'GUILD_MODULE_PANELS_UPDATE']);

// whether a bot session with these intents receives event t with payload d
export function wants(intents, t, d, botId) {
  if (USER_ONLY.has(t)) return false;
  if (t === 'GUILD_MEMBER_UPDATE' && d?.user?.id === botId) return true; // own member updates come regardless (docs caveat)
  const bits = SPLIT[t] ? SPLIT[t][d?.guild_id ? 0 : 1] : ONE[t];
  return bits === undefined || (intents & bits) !== 0;
}

// MESSAGE_CONTENT rules: without the intent a bot sees content only in its own messages, DMs and messages mentioning it
export function redact(m, botId) {
  if (!m?.guild_id || m.author?.id === botId || m.mentions?.some(u => u.id === botId)) return m;
  const { poll, ...rest } = m;
  return { ...rest, content: '', embeds: [], attachments: [], components: [], ...(m.message_snapshots && { message_snapshots: [] }) };
}
