export const I = {
  GUILDS: 1 << 0, GUILD_MEMBERS: 1 << 1, GUILD_MODERATION: 1 << 2, GUILD_EXPRESSIONS: 1 << 3, GUILD_INTEGRATIONS: 1 << 4,
  GUILD_WEBHOOKS: 1 << 5, GUILD_INVITES: 1 << 6, GUILD_VOICE_STATES: 1 << 7, GUILD_PRESENCES: 1 << 8, GUILD_MESSAGES: 1 << 9,
  GUILD_MESSAGE_REACTIONS: 1 << 10, GUILD_MESSAGE_TYPING: 1 << 11, DIRECT_MESSAGES: 1 << 12, DIRECT_MESSAGE_REACTIONS: 1 << 13,
  DIRECT_MESSAGE_TYPING: 1 << 14, MESSAGE_CONTENT: 1 << 15, GUILD_SCHEDULED_EVENTS: 1 << 16, AUTO_MODERATION_CONFIGURATION: 1 << 20,
  AUTO_MODERATION_EXECUTION: 1 << 21, GUILD_MESSAGE_POLLS: 1 << 24, DIRECT_MESSAGE_POLLS: 1 << 25,
};
export const ALL_INTENTS = Object.values(I).reduce((a, b) => a | b);
export const PRIVILEGED = I.GUILD_MEMBERS | I.GUILD_PRESENCES | I.MESSAGE_CONTENT;

// application flags that unlock the privileged intents (either the large-bot or the "limited" bit)
export const APP_FLAGS = {
  GATEWAY_PRESENCE: 1 << 12, GATEWAY_PRESENCE_LIMITED: 1 << 13, GATEWAY_GUILD_MEMBERS: 1 << 14,
  GATEWAY_GUILD_MEMBERS_LIMITED: 1 << 15, GATEWAY_MESSAGE_CONTENT: 1 << 18, GATEWAY_MESSAGE_CONTENT_LIMITED: 1 << 19,
};
export const SETTABLE_APP_FLAGS = APP_FLAGS.GATEWAY_PRESENCE_LIMITED | APP_FLAGS.GATEWAY_GUILD_MEMBERS_LIMITED | APP_FLAGS.GATEWAY_MESSAGE_CONTENT_LIMITED;

export function privilegedAllowed(flags) {
  const on = (a, b) => (flags & (a | b)) !== 0;
  return (on(APP_FLAGS.GATEWAY_PRESENCE, APP_FLAGS.GATEWAY_PRESENCE_LIMITED) ? I.GUILD_PRESENCES : 0)
    | (on(APP_FLAGS.GATEWAY_GUILD_MEMBERS, APP_FLAGS.GATEWAY_GUILD_MEMBERS_LIMITED) ? I.GUILD_MEMBERS : 0)
    | (on(APP_FLAGS.GATEWAY_MESSAGE_CONTENT, APP_FLAGS.GATEWAY_MESSAGE_CONTENT_LIMITED) ? I.MESSAGE_CONTENT : 0);
}

